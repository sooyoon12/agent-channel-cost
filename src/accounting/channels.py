"""I/T/O channel classification.

Classification is based on the billing event, not merely on an item's original
author. A replayed assistant tool call is I; a tool result remains T whenever it
is sent as input; output created by the current model request is O.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Any, Iterable, Mapping, Protocol


class Channel(str, Enum):
    INSTRUCTION_HISTORY = "I"
    TOOL_OBSERVATION = "T"
    NEW_OUTPUT = "O"


@dataclass(frozen=True)
class ClassifiedContent:
    channel: Channel
    kind: str
    item: Mapping[str, Any]


class JsonTokenCounter(Protocol):
    def count_json(self, value: Any) -> int: ...


@dataclass(frozen=True)
class ChannelTokenCounts:
    i_tokens: int
    t_tokens: int
    item_count: int

    @property
    def total_input_tokens(self) -> int:
        return self.i_tokens + self.t_tokens


_TOOL_RESULT_TYPES = frozenset(
    {
        "tool_result",
        "tool_output",
        "function_call_output",
        "computer_call_output",
        "web_search_call_output",
        "file_search_call_output",
        "mcp_call_output",
        "code_interpreter_call_output",
    }
)

_CURRENT_OUTPUT_TYPES = frozenset(
    {
        "message",
        "reasoning",
        "function_call",
        "computer_call",
        "web_search_call",
        "file_search_call",
        "mcp_call",
        "code_interpreter_call",
        "custom_tool_call",
    }
)

_INSTRUCTION_METADATA_TYPES = frozenset(
    {
        "tool_schema",
        "tool_definition",
        "response_format",
        "developer_instruction",
    }
)


def _type(item: Mapping[str, Any]) -> str:
    value = item.get("type", "message")
    return str(value).strip().lower()


def _role(item: Mapping[str, Any]) -> str | None:
    value = item.get("role")
    return None if value is None else str(value).strip().lower()


def _looks_like_tool_result(item_type: str) -> bool:
    # Provider-native result items consistently use a *_call_output suffix.
    return item_type in _TOOL_RESULT_TYPES or item_type.endswith("_call_output")


def classify_input_item(item: Mapping[str, Any]) -> ClassifiedContent:
    """Classify one item included in a model request as exactly I or T.

    Unknown input item types default to I only when they have a recognized
    conversational role. Completely unknown shapes fail closed so new provider
    protocol items cannot silently corrupt the accounting.
    """

    item_type = _type(item)
    role = _role(item)
    if role in {"tool", "function"} or _looks_like_tool_result(item_type):
        return ClassifiedContent(Channel.TOOL_OBSERVATION, item_type, item)
    if role in {"system", "developer", "user", "assistant"}:
        return ClassifiedContent(Channel.INSTRUCTION_HISTORY, item_type, item)
    if item_type in _INSTRUCTION_METADATA_TYPES:
        return ClassifiedContent(Channel.INSTRUCTION_HISTORY, item_type, item)
    if item_type in _CURRENT_OUTPUT_TYPES:
        # These are replayed provider items because this function only accepts
        # content already present in the next request.
        return ClassifiedContent(Channel.INSTRUCTION_HISTORY, item_type, item)
    raise ValueError(f"unrecognized input item shape: role={role!r}, type={item_type!r}")


def classify_output_item(item: Mapping[str, Any]) -> ClassifiedContent:
    """Classify an item newly generated by the current model request as O."""

    item_type = _type(item)
    role = _role(item)
    if _looks_like_tool_result(item_type) or role in {"tool", "function"}:
        raise ValueError("tool results are environment input, not newly generated model output")
    if role == "assistant" or item_type in _CURRENT_OUTPUT_TYPES:
        return ClassifiedContent(Channel.NEW_OUTPUT, item_type, item)
    raise ValueError(f"unrecognized output item shape: role={role!r}, type={item_type!r}")


def count_input_channels(
    items: Iterable[Mapping[str, Any]], tokenizer: JsonTokenCounter
) -> ChannelTokenCounts:
    """Count canonical item content, keeping provider framing in residual."""

    i_tokens = 0
    t_tokens = 0
    item_count = 0
    for item in items:
        classified = classify_input_item(item)
        tokens = tokenizer.count_json(item)
        if tokens < 0:
            raise ValueError("tokenizer returned a negative count")
        if classified.channel is Channel.INSTRUCTION_HISTORY:
            i_tokens += tokens
        else:
            t_tokens += tokens
        item_count += 1
    return ChannelTokenCounts(i_tokens, t_tokens, item_count)
